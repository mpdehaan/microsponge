"""The guide pages of the themes: where each lives, and the appendix of tables that the tools generate into it.

Each theme has a guide, `GUIDE_<THEME>.md` at the top of the repository, written by hand for the
people who play the game: what the theme is like, its story and its tips. The guide ends with an
appendix of tables that come from the code, the units, the buildings, the world wonders, the
tech tree and the balance of the units, between two marker comments, so that the tables are
always true and the words around them are never touched by a tool.
"""

from pathlib import Path

from microsponge.engine.kinds.kind import saved_name, shown_name
from microsponge.support.balance_report import report as balance_report
from microsponge.support.kind_reports import buildings_report, tech_report, units_report, wonders_report
from microsponge.ui_strings import MSG_GUIDE_APPENDIX, MSG_GUIDE_APPENDIX_NOTE

GUIDE_FILE = 'GUIDE_{theme}.md'
START_MARKER = '<!-- generated by tools/theme_guides.py: start -->'
END_MARKER = '<!-- generated by tools/theme_guides.py: end -->'
LINE_END = '\n'
BLANK_LINE = ''
# The reports that make up the appendix, in the order they appear.
REPORTS = (units_report, buildings_report, wonders_report, tech_report, balance_report)


def guide_path(*, root, theme):
    """Return the path of a theme's guide under the repository root: GUIDE_CAVEMAN.md for caveman."""
    return Path(root) / GUIDE_FILE.format(theme=saved_name(theme).upper())


def appendix_lines(theme):
    """Return the generated appendix of a theme's guide, markers included, as lines."""
    lines = [START_MARKER, MSG_GUIDE_APPENDIX.format(theme=shown_name(theme)), BLANK_LINE, MSG_GUIDE_APPENDIX_NOTE]
    for report in REPORTS:
        lines += [BLANK_LINE, *report(theme, markdown=True)]
    lines += [END_MARKER]
    return lines


def with_appendix(*, text, theme):
    """Return a guide's text with its appendix replaced by the current one, or the appendix added at the end when the guide has none."""
    appendix = LINE_END.join(appendix_lines(theme))
    if START_MARKER in text and END_MARKER in text:
        before = text[:text.index(START_MARKER)]
        after = text[text.index(END_MARKER) + len(END_MARKER):]
        return before + appendix + after
    return text.rstrip(LINE_END) + LINE_END * 2 + appendix + LINE_END


def is_current(*, path, theme):
    """Return whether a guide's appendix is what the code generates now."""
    text = Path(path).read_text()
    return with_appendix(text=text, theme=theme) == text


def refresh(*, path, theme):
    """Rewrite a guide's appendix from the code, and return whether anything changed."""
    text = Path(path).read_text()
    refreshed = with_appendix(text=text, theme=theme)
    if refreshed == text:
        return False
    Path(path).write_text(refreshed)
    return True
